/**
 * Calculates duration in hours between "HH:MM" and "HH:MM"
 */
export function calculateDurationHours(startTime: string, endTime: string): number {
  const [startH, startM] = startTime.split(':').map(Number);
  const [endH, endM] = endTime.split(':').map(Number);
  const startMinutes = startH * 60 + startM;
  const endMinutes = endH * 60 + endM;
  const diffMinutes = Math.max(0, endMinutes - startMinutes);
  return Number((diffMinutes / 60).toFixed(2));
}

/**
 * Formats duration to readable text, e.g. "2h" or "1h 30m"
 */
export function formatDurationText(hours: number): string {
  const h = Math.floor(hours);
  const m = Math.round((hours - h) * 60);
  if (m === 0) return `${h}h`;
  if (h === 0) return `${m}p`;
  return `${h}h ${m}p`;
}

/**
 * Formats currency in VND
 */
export function formatVND(amount: number): string {
  return new Intl.NumberFormat('vi-VN', {
    style: 'currency',
    currency: 'VND',
    maximumFractionDigits: 0,
  }).format(amount);
}
